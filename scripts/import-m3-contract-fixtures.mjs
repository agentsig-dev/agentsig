import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

// Record independently authored expectations before production implementation.
// No network, production imports, TLS regeneration, or inferred test outcomes.
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const directory = resolve(root, "tests/fixtures/m3-contract");
const hash = (bytes) => createHash("sha256").update(bytes).digest("hex");
const names = [
    "fetch-cache-cases.json",
    "recovery-cases.json",
    "redis-cases.json",
    "f3-classification-cases.json",
    "tls/server-cert.pem",
    "tls/server-key.pem",
];
const files = names.map((path) => {
    const file = resolve(directory, path);
    // Only locally authored text is normalized. Upstream sources stay untouched.
    const bytes = Buffer.from(readFileSync(file, "utf8").replace(/\r\n/g, "\n"));
    if (path.endsWith(".json")) {
        const value = JSON.parse(bytes);
        assert.equal(value.formatVersion, 1);
        assert.equal(value.approvedOn, "2026-09-19");
    }
    writeFileSync(file, bytes);
    return {
        path,
        bytes: bytes.length,
        sha256: hash(bytes),
        provenance: path.startsWith("tls/")
            ? "Locally generated public TLS test material; pinned bytes, not regenerated by this script"
            : "Independently authored expectations from maintainer-approved M3 decisions",
        license: "MIT",
    };
});
const pinned = JSON.parse(readFileSync(resolve(root, "tests/fixtures/m3/manifest.json")));
const sourceNames = [
    "sources/wg-5.5.txt",
    "sources/wg-appendix-c.txt",
    "sources/wg-6.7-6.10.txt",
    "cloudflare/web_bot_auth_architecture_v2.json",
];
const sources = sourceNames.map((path) => {
    const entry = pinned.files.find((file) => file.path === path);
    assert(entry, path);
    const sourcePath = `tests/fixtures/m3/${path}`;
    assert.equal(hash(readFileSync(resolve(root, sourcePath))), entry.sha256, sourcePath);
    return { path: sourcePath, sha256: entry.sha256 };
});
const manifest = {
    formatVersion: 1,
    authoredOn: "2026-09-19",
    productionImplementationExists: false,
    warning: "PUBLIC TEST PRIVATE KEY. Never use this certificate or key in production.",
    scope: "Pre-implementation contracts and local test infrastructure, not proof of implemented SSRF or Redis protection",
    tls: {
        hostname: "directory.agentsig.test",
        notBefore: "2026-09-19T17:24:33Z",
        notAfter: "2036-09-16T17:24:33Z",
        trust: "Explicit test-client CA configuration only; no system trust-store modification",
        productionAddressPolicyBypass: false,
    },
    sources,
    files,
};
writeFileSync(resolve(directory, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
console.log(`M3 contracts: ${files.length} expectation/TLS files recorded; source hashes verified.`);